// The words the keyword fallback understands. Data only — the matching lives
// in keyword-classifier.ts.
//
// Every keyword is written the way people type it; the classifier folds both
// the keyword and the message through normalizeArabic (hamza, ة/ه, ى/ي) and
// allows the usual glued prefixes (ال، و، ب، ل، ف، ك), so "الصيدليه" and
// "وصيدلية" need no entry of their own. Longest match wins across every
// table, so a specific phrase ("صيانة جوالات") beats the general word inside
// it ("جوالات") without any ordering rules here.
//
// Built from what the simulation agents asked (scripts/agent-corpus), and
// from Flutter's offline table (lib/services/intent_service.dart), which it
// supersedes for every app version that reaches the server.

/** A fixed category: one of CATEGORIES, searched by its own Google type. */
export interface FixedPlace {
  slug: string;
  words: string[];
}

/** A place with no fixed category. Becomes category "other" with this tag,
 * and the label is what Google Text Search is asked for. */
export interface FreePlace {
  key: 'amenity' | 'shop' | 'leisure' | 'tourism' | 'office' | 'craft';
  value: string;
  label: string;
  words: string[];
}

/** A need described instead of named ("الحمام مسدود") → the trade that fixes
 * it. Matched alongside the profession registry's own names and aliases. */
export interface ProblemWords {
  profession: string;
  words: string[];
}

