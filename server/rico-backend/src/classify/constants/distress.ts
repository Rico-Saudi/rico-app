// كلام عن أذية النفس يُجاب هنا قبل أي نداء للنموذج.
//
// النموذج يفهم "بدي موت؟" صح لما يوصله — بس يوصله مش دايماً: البرومبت وحده
// قريب من سقف التوكنات بالدقيقة على Groq، فالرسالة التانية بنفس الدقيقة
// بترجع 429 والعميل بيسقط على مطابقته المحلية. وأغلى غلط بالتطبيق كله هو
// رد «ما فهمتك» على إنسان بهالحالة. رد الأمان ما بيستاهل يعتمد على شبكة ولا
// حدّ استخدام، فبيطلع من هون، ثابت بلا تنويع ولا نصيحة طبية.
//
// النمط مكتوب بالصيغة المطبَّعة (بلا همزات، ه بدل ة، ي بدل ى) ويُطابَق على
// الرسالة بعد normalizeArabic، فـ"بدي أموت" و"بدي اموت" و"بدي موت؟؟" و"تعبت
// من حياتى" كلها صيغة وحدة. مرآة لـ _distressPattern في التطبيق
// (lib/services/intent_service.dart) — تعديل هون غالباً إله أخ هناك.
import { Brand } from '../../common/constants/brands';
import { normalizeArabic } from '../../learning/constants/normalize';

// "موت" بلا ألف مقبولة (هي الصيغة المنطوقة فعلاً) بشرط نهاية كلمة بعدها،
// وإلا انلقطت "بدي موتور" و"أبي موتر". والمبالغات ("أموت من الجوع/الضحك")
// جوع ودردشة مش ضيق، فمستثناة.
const DISTRESS = new RegExp(
  '(?:ابي|بدي|ابغي|ودي|نفسي|عايز|عاوز)\\s*(?:اموت|موت|انتحر)(?=$|\\s)' +
    '(?!\\s*من\\s*(?:الجوع|الضحك|الحر|البرد|العطش|النعاس|الفرح|الشبع|الملل|الزحمه|الطفش))|' +
    'تعبت من حياتي|مليت من حياتي|زهقت من حياتي|كرهت حياتي|طفشت من حياتي|' +
    'تعبت من الحياه|مليت من الحياه|زهقت من الحياه|كرهت الحياه|' +
    'ما ابي اعيش|ما بدي اعيش|ما ابغي اعيش|' +
    'اذي نفسي|ااذي حالي|اذي حالي|اوذي نفسي|انهي حياتي|انتحر|انتحار',
);

// التطويل بالتكرار ("أمووت"، "موووت") يُطوى هون لا في normalizeArabic: تلك
// مفتاح تجميع للفجوات المحفوظة، وتغييرها بيفرّق صفوفاً قديمة عن جديدة.
function collapseElongation(s: string): string {
  return s.replace(/(.)\1{2,}/gu, '$1').replace(/([وا])\1/g, '$1');
}

export function isDistress(message: string): boolean {
  return DISTRESS.test(collapseElongation(normalizeArabic(message)));
}

const SAUDI_DISTRESS_REPLY =
  'والله آسف إنك حاسّ كذا 🤍 تكلّم مع شخص تثق فيه أو مع دكتور، ولا تظل لحالك بهالإحساس. وإذا تبي أدلّك على أقرب عيادة أو مستشفى، قل لي وأنا أطلّع لك إياها.';
const JORDANIAN_DISTRESS_REPLY =
  'والله آسف إنك حاسس هيك 🤍 احكي مع حدا بتثق فيه أو مع دكتور، ولا تضل لحالك بهالإحساس. وإذا بدك أدلّك على أقرب عيادة أو مستشفى، احكيلي وأنا بطلّعلك إياها.';

export function distressReplyFor(brand: Brand): string {
  return brand.dialect === 'jordanian' ? JORDANIAN_DISTRESS_REPLY : SAUDI_DISTRESS_REPLY;
}
