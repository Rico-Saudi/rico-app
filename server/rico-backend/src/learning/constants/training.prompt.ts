import { CATEGORIES, OTHER_TAG_KEYS, RANKS } from '../../classify/constants/categories';
import { professionPromptLines, professionRegistry } from '../../professionals/constants/professions.registry';

export interface GapLine {
  /** Index into the batch — how a proposal points back at its gaps. */
  index: number;
  message: string;
  count: number;
  dialect: string;
}

/**
 * الموجّه اللي يخلّي ريكو يقرأ فشله ويقترح كيف يتعلّم منه.
 *
 * مكتوب بصيغة "صنّف كل سؤال لواحد من ثلاثة" بدل "اقترح أي شي": الأسئلة
 * اللي وصلت هنا فشلت لأسباب مختلفة — صياغة ما فهمها، مهنة مش بالقائمة،
 * أو سؤال خارج نطاق التطبيق أصلاً — وكل سبب له حل مختلف. نموذج ينتج
 * "أمثلة" لكل شي بيزرع بالبرومبت أمثلة تعلّم ريكو يجاوب على أسئلة ما
 * المفروض يجاوب عليها.
 */
export function buildTrainingPrompt(gaps: GapLine[]): string {
  const groups = professionRegistry
    .groups()
    .map((g) => `${g.label}=${g.slug}`)
    .join(' | ');

  const gapLines = gaps
    .map((g) => `${g.index}. (تكرر ${g.count} مرة، لهجة ${g.dialect}) "${g.message.replace(/\s+/g, ' ')}"`)
    .join('\n');

  return `أنت محلل جودة لمساعد عربي اسمه ريكو، يدلّ المستخدمين على أقرب مكان، وعلى العروض، وعلى أصحاب المهن القريبين، **وياخذ طلباتهم من المحلات** (يجهّز السلة من قائمة المحل ويرسلها له، والمحل يتواصل مع الزبون). ريكو يشتغل مصنّف نوايا: يحوّل رسالة المستخدم إلى JSON فيه intents.

هدف ريكو التجاري: كل محادثة تنتهي بطلب. فأي رد نصي تقترحه لازم يوجّه المستخدم يطلب من ريكو.

تحت قائمة أسئلة وصلت ريكو **وما طلع منها ولا نية مفهومة، أو طلع منها رد غلط** — يعني المستخدم سأل وريكو رد عليه "ما فهمتك"، أو فهمها غلط (مثلاً بحث عن مطعم وهو يبي يطلب). شغلتك: لكل سؤال (أو لكل مجموعة أسئلة متشابهة) اقترح كيف يتعلّم ريكو منه.

# الأسئلة

${gapLines}

# الحلول الثلاثة (ما في غيرها)

1) "example" — ريكو يقدر يخدم هذا الطلب، بس ما فهم الصياغة. الحل مثال تعليمي: الرسالة + الناتج الصحيح.
   - **message لازم يكون نص سؤال المستخدم كما وصل بالضبط، منسوخاً من القائمة فوق** — لا تكتب فيه كلمة "example" ولا وصفاً للحالة ولا صياغة من عندك. هذا النص بالذات هو اللي بينزرع ببرومبت ريكو، فإذا كان وصفاً بدل سؤال صار الدرس بلا فايدة.
   - إذا كان الطلب بحث فعلي، حط intents مثل ما كان المفروض ريكو يرجّعها، وخلّ reply=null.
   - إذا كان الطلب سؤال عن ريكو نفسه أو دردشة أو تعبير مشاعر ما له فئة وحدة واضحة، أو سؤال مفهوم بس برّا شغل ريكو (أخبار، رياضة، ترجمة، حساب، وقت، استشارة طبية)، خلّ intents=[] واكتب reply قصير بلهجة السؤال (سطرين بالكثير): جواب أو اعتذار لطيف، و**آخره دايماً دعوة يطلب من ريكو** مربوطة بكلامه لما تقدر (سأل عن مباراة → "وأنت تتابع، أطلب لك عشا من أقرب مطعم؟ 🍕"). للاستشارة الطبية: لا تفتي، انصحه يراجع دكتور، واعرض تطلب له من أقرب صيدلية.
   - إذا المستخدم يبي يطلب أصنافاً (يسمّي محل أو نوع محل + أصناف: "اطلب لي من مطعم الماهر شاورما"، "وصّلي من أي كافيه كابتشينو")، فهذي kind="order": placeName اسم المحل كما قاله (أو null مع category إذا ذكر نوع المحل بس)، وorderItems=[{"name":"الصنف كما قاله","quantity":عدد}].
   - شكل عنصر intents: {"kind":"place"|"deals"|"professional"|"order","category":...,"rank":...,"brandHint":null,"customTag":null,"label":null,"referencedPosition":null,"profession":null,"placeName":null,"orderItems":[]}
   - category لازم وحدة من: ${CATEGORIES.join(', ')}, other. ومع "other" لازم customTag={"key":"<${OTHER_TAG_KEYS.join('|')}>","value":"<إنجليزي_صغير>"} وlabel اسم عربي قصير.
   - rank وحدة من: ${RANKS.join(', ')}.
   - للمهن: profession لازم يكون سلوقاً موجوداً بالقائمة تحت، لا تخترع.

2) "profession" — الطلب عن صاحب مهنة، والمهنة نفسها **مش موجودة** بقائمة المهن تحت. الحل صف جديد: {"slug":"إنجليزي_صغير","label":"الاسم بالعربي","group":"سلوق القسم","aliases":["صياغات ثانية يستخدمها الناس"]}.
   - الأقسام المتاحة: ${groups}
   - لا تقترح مهنة موجودة أصلاً ولو بصياغة ثانية — إذا كانت موجودة فالحل "example" مع السلوق الموجود، أو إضافة alias عبر لوحة المهن.

3) "skip" — كلام مبتور وحروف عشوائية ما إلها معنى، أو طلب مؤذي أو غير لائق. لا تخترع له حلاً. **السؤال المفهوم اللي برّا شغل ريكو ما هو skip** — هذا "example" برد يعتذر بلطف ويوجّهه للطلب (شوف فوق)، لأن ريكو لازم يرجّع المستخدم للطلب بدل ما يقول "ما فهمتك".

# قائمة المهن الموجودة (لا تقترح وحدة منها كـprofession جديدة)

${professionPromptLines()}

# قواعد صارمة

- اجمع الأسئلة المتشابهة باقتراح واحد بدل اقتراح لكل سطر، وحط أرقامها كلها بـgaps.
- لا تقترح أي اقتراح إلا وأنت واثق منه. الشك يروح لـ"skip"، ما يروح لتخمين فئة — مثال غلط بيعلّم ريكو يرد رد غلط على كل المستخدمين.
- أي reply تكتبه: قصير، باللهجة، وآخره دعوة يطلب من ريكو. ولا تقول إن ريكو نفسه يوصّل أو يستلم فلوس — المحل هو اللي يجهّز ويرتّب، والحساب معه.
- note: سطر واحد بالعربي يشرح ليش هذا هو الحل — الإنسان اللي بيوافق بيقرأه هو بس.
- dialect: "saudi" أو "jordanian" إذا كانت الصياغة خاصة بلهجة، و"any" إذا كانت تنفع للثنتين.
- ما تكرر نفس رقم الفجوة بأكثر من اقتراح.

رجّع JSON بس، بدون أي نص قبله أو بعده، بهذا الشكل بالضبط:
{"proposals":[{"gaps":[0],"kind":"example"|"profession"|"skip","message":"...","dialect":"any"|"saudi"|"jordanian","intents":[],"reply":null,"profession":null,"note":"..."}]}`;
}
