/// يطوي الصيغ المختلفة لكتابة نفس الكلمة إلى صيغة واحدة، للمطابقة المحلية فقط.
///
/// نفس المستخدم يكتب "بدي أموت" مرة و"بدي اموت" مرة و"بدي أمووت؟؟" مرة،
/// وكلها عنده سؤال واحد. أنماط المطابقة في [IntentService] كانت تعدّد الهمزة
/// وغير الهمزة يدوياً في كل نمط ("أموت|اموت")، فأي صيغة ما خطرت على بال كاتب
/// النمط تسقط على «ما فهمتك». الطيّ هنا يحل الصنف كله بدل كل حالة على حدة.
///
/// مرآة لـ normalizeArabic في الخادم (learning/constants/normalize.ts) مع
/// إضافة واحدة: طيّ الحروف المكرّرة للتطويل ("أمووت"، "جوووعان")، لأن المطابقة
/// هنا تُقارن أنماطاً لا تجمع إحصاءً.
///
/// النص الناتج لا يُعرض لأحد ولا يُرسل للخادم — فقدان "ة"/"ه" مقصود ومقبول
/// للمطابقة، وغير مقبول في أي نص يقرأه إنسان.
library;

// التشكيل والألف الخنجرية والتطويل (ـ).
final RegExp _diacritics = RegExp('[ؐ-ًؚ-ٰٟۖ-ۭـ]');

// الأرقام العربية والفارسية.
final RegExp _arabicDigits = RegExp('[٠-٩۰-۹]');

// أي شي غير حرف أو رقم أو مسافة: ترقيم، إيموجي، "؟؟؟" و"!!!".
final RegExp _nonWord = RegExp(r'[^\p{L}\p{N}\s]', unicode: true);

// تطويل: نفس الحرف ثلاث مرات أو أكثر ("موووت")، أو واو/ألف مكرّرة مرتين
// ("أمووت"، "جووعان"). الياء المكرّرة مستثناة لأنها صيغة صحيحة كثيراً
// ("كهربائيين")، والمضاعفة الصحيحة في العربية تُكتب بالشدّة لا بالتكرار —
// ما عدا "الله" و"اللي" (لام التعريف + لام الكلمة) وهي لا تتأثر بقاعدة
// الواو والألف.
final RegExp _tripled = RegExp(r'(.)\1{2,}', unicode: true);
final RegExp _doubledLong = RegExp('([وا])\\1');

final RegExp _spaces = RegExp(r'\s+');

/// طيّ الحروف وحده، بلا مسّ الترقيم ولا التكرار. يُطبَّق على *مصدر الأنماط*
/// كذلك لا على النص فقط: نمط فيه "كهربائي" ما يطابق نصاً طُوي إلى "كهربايي"
/// إلا إذا طُوي النمط بنفس القاعدة. آمن على مصدر RegExp لأن ما يُبدَّل هنا
/// حروف عربية وتشكيل، وما منها رمز له معنى في الأنماط.
String foldArabicLetters(String s) => s
    .replaceAll(_diacritics, '')
    .replaceAll(RegExp('[آأإاٱ]'), 'ا')
    .replaceAll('ى', 'ي')
    .replaceAll('ة', 'ه')
    .replaceAll('ؤ', 'و')
    .replaceAll('ئ', 'ي');

String normalizeArabic(String raw) {
  var s = raw;
  // طيّ التكرار قبل طيّ الحروف لا بعده: "كهربائيين" بعد تحويل ئ→ي تصير ثلاث
  // ياءات متتالية وتُطوى لياء واحدة، مع إنها ما فيها أي تطويل.
  s = s.replaceAllMapped(_tripled, (m) => m[1]!);
  s = s.replaceAllMapped(_doubledLong, (m) => m[1]!);
  s = foldArabicLetters(s);
  s = s.replaceAllMapped(_arabicDigits, (m) => (m[0]!.codeUnitAt(0) & 0xf).toString());
  s = s.replaceAll(_nonWord, ' ');
  return s.replaceAll(_spaces, ' ').trim().toLowerCase();
}
