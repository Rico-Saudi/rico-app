/// نمط رسالة دردشة (غير بحث) + الردود الممكنة عليه — انظر
/// [IntentService.detectOffTopicReply].
class _ChatReply {
  final RegExp pattern;
  final List<String> replies;

  /// هل نضيف سطر تشجيع في نهاية الرد؟ كل رد لازم ينتهي بدعوة للاستخدام، لكن
  /// الردود اللي أصلاً تنتهي بسؤال مباشر (تحية، شكر، مدح، "شو بدك؟") تكتفي
  /// بسؤالها — إضافة سطر ثاني عليها يطلّع سؤالين ورا بعض بلا فايدة.
  final bool appendCta;

  const _ChatReply(this.pattern, this.replies, {this.appendCta = true});
}

/// طريقة ترتيب النتائج المطلوبة. best_rated غير مفعّلة فعلياً بعد (تحتاج
/// بيانات تقييم حقيقية غير متوفرة دوماً).
enum RankMode { nearest, cheapest, openNow, bestRated }

/// نوع النية: بحث عن مكان، أو استفسار عن عروض/خصومات (لا يرتبط بفئة مكان)،
/// أو طلب **شخص** صاحب مهنة (دهان، كهربائي...) وهذا غير المحل الذي يبيع
/// أدوات المهنة نفسها — انظر [IntentService.professionFor].
enum IntentKind { place, deals, professional, order, call }

/// صنف طلبه المستخدم بالاسم ضمن نية [IntentKind.order] — كما نطقه هو، بلا
/// تصحيح: المطابقة مع قائمة المحل الحقيقية تصير على الخادم.
class RequestedItem {
  final String name;
  final int quantity;

  const RequestedItem({required this.name, this.quantity = 1});

  Map<String, dynamic> toJson() => {'name': name, 'quantity': quantity};
}

/// نية واحدة من نوايا رسالة المستخدم (قد تحتوي الرسالة الواحدة عدة نوايا،
/// انظر [IntentService.parseMulti]).
class QueryIntent {
  final IntentKind kind;
  final String label; // اسم عربي مفهوم للعرض في الرد
  final RankMode rank;
  final String? brandHint;
  final String? slug; // null لنوايا deals وللفئات الحرة (other) غير الثابتة

  /// سلوق المهنة لنوايا [IntentKind.professional] فقط — null لغيرها.
  final String? profession;

  /// اسم المحل — لنوايا [IntentKind.order] و[IntentKind.call]. والأصناف
  /// المطلوبة لـ[IntentKind.order] فقط.
  final String? placeName;
  final List<RequestedItem> orderItems;

  /// رقم ترتيب عنصر من "آخر نتائج معروضة" أشار له المستخدم صراحة (مثل
  /// "الثاني")، أو null لطلب بحث عادي. عند تحديده يُحل من الذاكرة المحلية
  /// (بدون بحث شبكي جديد) في شاشة الدردشة.
  final int? referencedPosition;

  QueryIntent({
    this.kind = IntentKind.place,
    required this.label,
    this.rank = RankMode.nearest,
    this.brandHint,
    this.slug,
    this.profession,
    this.referencedPosition,
    this.placeName,
    this.orderItems = const [],
  });

  bool get wantsCheapest => rank == RankMode.cheapest;
  bool get wantsOpenNow => rank == RankMode.openNow;
}

