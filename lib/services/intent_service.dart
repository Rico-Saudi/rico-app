  /// التطبيق هو الرد على إنسان بهذي الحالة بـ«ما فهمتك» لأن الخادم تجاوز حدّ
  /// الاستخدام. والنموذج ما يضيف شيئاً هنا — الرد ثابت عمداً بلا تنويع ولا
  /// نصيحة طبية.
  ///
  /// رسالة فيها إشارة بحث ("تعبت من حياتي وبدي صيدلية") تُترك للمصنّف الذي
  /// يرى السياق كله — نفس الحكم في [isWeatherQuestion].
  static String? distressReply(String text, {String? lastCategorySlug}) {
    final trimmed = text.trim();
    if (!_matches(_distressPattern, trimmed)) return null;
    if (hasSearchSignal(trimmed, lastCategorySlug: lastCategorySlug)) return null;
    return _distressReply.replies.first;
  }

  static String? detectOffTopicReply(String text) {
    final trimmed = text.trim();
    final seed = trimmed.hashCode.abs();
    for (final entry in _chatReplies) {
      if (_matches(entry.pattern, trimmed)) {
        final body = entry.replies[seed % entry.replies.length];
        if (!entry.appendCta) return body;
        return '$body\n\n${_ctaLines[(seed ~/ 7) % _ctaLines.length]}';
      }
    }
    return null;
  }

  /// يطابق اسم مهنة في النص، أو null. مسار محلي احتياطي فقط: المصنّف عبر
  /// LLM هو من يفرّق عادة بين "أبغى دهان" و"وين محل دهانات"، وهذا يفعل نفس
  /// التمييز بقاعدة واحدة بسيطة — وجود كلمة تدل على محل ([_shopWords]) يعني
  /// أن المقصود مكان لا شخص.
  ///
  /// أطول صيغة مطابقة تفوز لنفس سبب فوزها في [parse]: "تنظيف خزانات" أخص من
  /// "تنظيف".
  static Profession? professionFor(String text) {
    if (_matches(_shopWords, text)) return null;

    Profession? chosen;
    var chosenLength = 0;
    for (final profession in ProfessionCatalog.all) {
      for (final alias in profession.aliases) {
        if (alias.length > chosenLength && _containsProfessionWord(text, alias)) {
          chosen = profession;
          chosenLength = alias.length;
        }
      }
    }
    if (chosen == null) return null;

    // "أطول مطابقة تفوز" مطبّقة عبر الجدولين لا داخل كل واحد وحده: "تنظيف"
    // مهنة و"تنظيف جاف" مغسلة، و"كهربائي" مهنة و"كهربائيات" محل. لما تطابق
    // كلمة مكان أطول، المقصود المكان — والعكس يخلي السؤال عن محل يُجاوَب
    // بقائمة أشخاص.
    return _longestPlaceWordMatch(text) >= chosenLength ? null : chosen;
  }

  /// يبني نية طلب صاحب مهنة من سلوق معروف — نظير [byCategorySlug] لنتيجة
  /// تصنيف LLM من نوع professional.
  static QueryIntent byProfessionSlug(String slug, {int? referencedPosition}) {
    final profession = ProfessionCatalog.bySlug(slug);
    // سلوق ما نعرفه = مهنة أُضيفت على الخادم بعد إصدار هذي النسخة. نمرّرها
    // كما هي بدل إسقاط النية: الخادم يعرف كيف يبحث عنها، وكل الناقص عندنا
    // هو الاسم العربي المصقول.
    return QueryIntent(
      kind: IntentKind.professional,
      label: profession?.label ?? slug,
      profession: slug,
      referencedPosition: referencedPosition,
    );
  }

  static RankMode _detectRank(String text) {
    if (RegExp(r'(?:فاتح|مفتوح|شغال)(?:ة|ه)?\s*(?:هلأ|هلا|هلق|الآن|الان|الحين)').hasMatch(text)) {
      return RankMode.openNow;
    }
    if (RegExp(r'أرخص|ارخص|أوفر|اوفر|رخيص').hasMatch(text)) {
      return RankMode.cheapest;
    }
    return RankMode.nearest;
  }

  /// يرجع `null` إذا لم تُطابق الرسالة أي فئة ولا مهنة ولا استكمال لطلب
  /// سابق. كان هنا افتراضي صامت بـ"مطعم"، وهو ما جعل أي سؤال غير مفهوم
  /// يُجاب ببحث عن مطاعم قريبة حين يفشل مصنّف الـLLM — سؤال بلا جواب أفضل
  /// من جواب عن سؤال ثانٍ. المستدعي مسؤول عن طلب التوضيح
  /// ([clarifyReply]).
  static QueryIntent? parse(String rawText, {String? lastCategorySlug}) {
    final text = rawText.trim();

    // اسم مهنة يُفحص قبل فئات الأماكن: "أبغى كهربائي" لازم تطلع طلب شخص، لا
    // تسقط على الافتراضي (مطعم) لأن ما فيها كلمة فئة مكان.
    final profession = professionFor(text);
    if (profession != null) {
      return QueryIntent(
        kind: IntentKind.professional,
        label: profession.label,
        profession: profession.slug,
      );
    }

    Map<String, Object>? chosen;

    // أطول كلمة مطابقة تفوز، مش أول فئة بالقائمة: "مغسلة ملابس" لازم تطلع
    // مغسلة ملابس مش محل ملابس، و"عيادة اسنان" تطلع عيادة أسنان مش عيادة
    // عامة. التعادل بالطول يفكّه ترتيب القائمة (الأخص موضوع قبل الأعم).
    var chosenWordLength = 0;
    for (final category in _categories) {
      for (final word in (category['words'] as String).split('|')) {
        if (word.length > chosenWordLength && _containsWord(text, word)) {
          chosen = category;
          chosenWordLength = word.length;
        }
      }
    }

    // لا كلمة فئة صريحة، لكن الرسالة تبدو استكمالاً لطلب سابق: أعد استخدام
    // آخر فئة معروفة بدل الرجوع الصامت لـ"مطعم" كافتراضي غير مبرر
    if (chosen == null && lastCategorySlug != null && _continuationWords.hasMatch(text)) {
      chosen = _categories.firstWhere(
        (c) => c['slug'] == lastCategorySlug,
        orElse: () => _categories.first,
      );
    }

    // لا فئة ولا مهنة ولا استكمال: ما فهمنا الرسالة. لا نخمّن.
    if (chosen == null) return null;

    return QueryIntent(
      label: chosen['label'] as String,
      rank: _detectRank(text),
      slug: chosen['slug'] as String,
    );
  }

  /// يفكك رسالة واحدة إلى عدة نوايا مستقلة إذا جمعت أكثر من طلب (مثال:
  /// "أقرب مطعم أو أرخص كافيه، وشو العروض الموجودة؟" → ٣ نوايا مستقلة).
  /// هذا مسار بديل محلي يُستخدم فقط عند فشل مصنّف الـLLM؛ لا يحاول فصل نية
  /// مكان عن نية عروض مذكورتين معاً داخل نفس الجزء النصي (مثال: "مطعم فيه
  /// عروض" تُعامل كنية عروض فقط) — الفصل الدقيق متروك لمصنّف الـLLM.
  static List<QueryIntent> parseMulti(String rawText, {String? lastCategorySlug}) {
    final text = rawText.trim();
    if (text.isEmpty) return [];

    final fragments = text
        .split(_intentSeparator)
        .map((f) => f.trim())
        .where((f) => f.isNotEmpty)
        .toList();

    if (fragments.isEmpty) {
      final single = parse(text, lastCategorySlug: lastCategorySlug);
      return single == null ? [] : [single];
    }

    // جزء غير مفهوم يُسقط ولا يُخمَّن: "أقرب مطعم و<كلام غامض>" تُجاب بالمطعم
    // وحده، لا بمطعمين. والقائمة الفارغة تعني أننا لم نفهم الرسالة إطلاقاً،
    // وهي إشارة للمستدعي أن يطلب توضيحاً بدل أن يبحث.
    final intents = <QueryIntent>[];
    for (final fragment in fragments) {
      if (_matches(_dealsWords, fragment)) {
        intents.add(QueryIntent(kind: IntentKind.deals, label: 'العروض'));
      } else {
        final intent = parse(fragment, lastCategorySlug: lastCategorySlug);
        if (intent != null) intents.add(intent);
      }
    }

    return intents.take(_maxIntents).toList();
  }

  /// يبني QueryIntent من فئة معروفة (slug)، تستخدم لتحويل نتيجة تصنيف LLM
  /// إلى نية بحث فعلية.
  static QueryIntent? byCategorySlug(
    String slug, {
    RankMode rank = RankMode.nearest,
    String? brandHint,
    int? referencedPosition,
  }) {
    for (final category in _categories) {
      if (category['slug'] == slug) {
        return QueryIntent(
          label: category['label'] as String,
          rank: rank,
          brandHint: brandHint,
          slug: slug,
          referencedPosition: referencedPosition,
        );
      }
    }
    return null;
  }
