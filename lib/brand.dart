/// هوية النسخة الإقليمية من التطبيق، وعنوان الخادم الذي تخدمها.
///
/// كل ما يفرّق نسخة سوق عن أخرى موجود هنا، وكله يُحدَّد وقت البناء لا بتعديل
/// الملف: فرعٌ واحد يخدم كل الأسواق، والفرق بين النسختين راية بناء.
///
/// ```sh
/// # السعودية (الافتراضي)
/// flutter build apk
///
/// # الأردن، على خادمها الخاص
/// flutter build apk \
///   --dart-define=RICO_BRAND=tadallal \
///   --dart-define=RICO_API=https://app.tadallal.com
///
/// # تجربة محلية: localhost لـ iOS Simulator وسطح المكتب،
/// # و10.0.2.2 لمحاكي أندرويد (localhost داخل المحاكي يشير لنفسه لا لجهازك)
/// flutter run --dart-define=RICO_API=http://localhost:3000
/// flutter run --dart-define=RICO_API=http://10.0.2.2:3000
/// ```
///
/// الاسم المعروض ما يجي من هنا: الخادم يملك خرائط slug ← اسم (انظر
/// brands.ts) عشان إضافة نسخة جديدة ما تحتاج إصدار تطبيق جديد للنسخ القديمة.
class Brand {
  const Brand._();

  /// المعرّف المرسل مع كل نداء تصنيف/صياغة/تحويل صوتي.
  ///
  /// يبقى مهماً حتى مع خادم لكل سوق: الخادم يقرأه ليعرف باسم مين يردّ، وبأي
  /// لهجة، وفي أي بلد يبحث.
  static const String slug = String.fromEnvironment(
    'RICO_BRAND',
    defaultValue: 'rico',
  );

  /// جذر الخادم الذي تنادي عليه كل خدمات التطبيق.
  ///
  /// كان مكتوباً حرفياً في أربعة عشر ملف خدمة، فالتبديل لخادم آخر — أو
  /// للتجربة المحلية — كان أربعة عشر تعديلاً يدوياً ونسيان واحد منها يعني
  /// تطبيقاً ينادي خادمين في وقت واحد. بلا خط مائل في النهاية.
  static const String apiBaseUrl = String.fromEnvironment(
    'RICO_API',
    defaultValue: 'https://app.rico-go.com',
  );
}
